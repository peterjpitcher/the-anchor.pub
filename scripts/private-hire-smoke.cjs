#!/usr/bin/env node
// Only connects to our isolated fixture server. Never accepts a remote target.
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const { chromium } = require('playwright')
const base = 'http://127.0.0.1:3138'
const output = '/tmp/anchor-growth/private-hire'
async function main() {
  await fs.mkdir(output, { recursive: true })
  const state = async query => (await fetch(`${base}/__private_hire_test${query || ''}`)).json()
  const initial = await state('?reject=true')
  const browser = await chromium.launch({ headless: true })
  const evidence = { checks: [], screenshots: [], consoleErrors: [], isolatedOnly: true }
  const context = await browser.newContext({ viewport: { width: 375, height: 900 }, extraHTTPHeaders: { 'x-forwarded-for': `192.0.2.${Math.floor(Math.random() * 250) + 1}` } })
  await context.route('**/*', async route => {
    const url = new URL(route.request().url())
    if (url.origin === base) return route.continue()
    if (url.hostname === 'challenges.cloudflare.com' && url.pathname.includes('/api.js')) return route.fulfill({ contentType: 'application/javascript', body: `const callbacks={};window.turnstile={render:(e,o)=>{const id='test-'+Object.keys(callbacks).length;callbacks[id]=o.callback;setTimeout(()=>o.callback('isolated-test-token'),0);return id},remove:()=>{},reset:id=>{setTimeout(()=>callbacks[id]?.('isolated-test-token'),0)},getResponse:()=> 'isolated-test-token',isExpired:()=>false,ready:f=>f(),execute:()=>{}};const cb=new URL(document.currentScript.src).searchParams.get('onload');if(cb&&window[cb])window[cb]();` })
    return route.abort()
  })
  const page = await context.newPage()
  page.setDefaultTimeout(20000)
  page.on('pageerror', error => evidence.consoleErrors.push(error.message))
  try {
    await page.goto(`${base}/private-hire`, { waitUntil: 'domcontentloaded', timeout: 120000 })
    const form = page.getByRole('form', { name: 'Short private hire enquiry' })
    await form.waitFor()
    await form.getByLabel('Occasion', { exact: true }).focus()
    const reject = page.getByRole('button', { name: /^(Reject All|Reject|Reject all cookies)$/i })
    await reject.waitFor()
    await reject.click()
    for (const width of [320, 375, 768, 1440]) {
      await page.setViewportSize({ width, height: 900 })
      await form.scrollIntoViewIfNeeded()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Overflow at ${width}px`)
      const file = `${output}/form-${width}.png`
      await page.screenshot({ path: file }); evidence.screenshots.push(file)
    }
    evidence.checks.push('No horizontal overflow at 320, 375, 768 and 1440 pixels')
    await page.setViewportSize({ width: 375, height: 900 })
    await form.getByLabel('Occasion', { exact: true }).fill('Synthetic party')
    await form.getByLabel('Approximate guests').fill('250')
    await form.getByLabel('Your name').fill('Isolated Test')
    await form.getByLabel('Phone number').fill('07700900000')
    await form.getByLabel('Notes (optional)').fill(`Synthetic context, no real enquiry, run ${Date.now()}`)
    const marketing = form.getByLabel(/Email me the latest/)
    assert.equal(await marketing.isChecked(), false)
    await marketing.check()
    await page.clock.install()
    await page.clock.fastForward(15000)
    assert.equal(await page.getByText('View Festive Packages', { exact: true }).count(), 0)
    evidence.checks.push('Active enquiry suppresses Christmas promotion beyond its ten-second timer')
    await form.getByRole('button', { name: 'Send enquiry', exact: true }).click()
    await form.getByRole('alert').filter({ hasText: 'Isolated test rejection' }).waitFor()
    assert.equal(await form.getByLabel('Your name').inputValue(), 'Isolated Test')
    evidence.checks.push('Actual website proxy error displayed; entered details and consent retained')
    const failed = await state('?reject=false')
    assert.equal(failed.requests.length, initial.requests.length + 1)
    // Two synchronous submits reproduce a quick duplicate without relying on button timing.
    await form.evaluate(element => { element.requestSubmit(); element.requestSubmit() })
    await page.getByRole('heading', { name: 'Enquiry received', exact: true }).waitFor()
    const final = await state()
    assert.equal(final.requests.length, initial.requests.length + 2)
    assert.equal(final.uniqueRecords, initial.uniqueRecords + 1)
    assert.equal(final.requests.at(-1).key, failed.requests.at(-1).key)
    const payload = final.requests.at(-1).payload
    assert.equal(payload.group_size, 250)
    assert.equal(payload.date, undefined)
    assert.ok(payload.notes.includes('Date undecided'))
    assert.ok(payload.notes.includes('Synthetic context'))
    assert.equal(payload.communication_consent.marketing_email_opt_in, true)
    assert.equal(payload.communication_consent.marketing_sms_opt_in, false)
    evidence.checks.push('Undecided date omitted, 250 guests and notes preserved, consent matches choice, retry key unchanged, double submit creates one isolated record')
    await page.clock.resume()
    await page.screenshot({ path: `${output}/received-mobile.png` })
    // The existing estimator still opens beside the short flow.
    await page.getByRole('button', { name: 'Open Cost Estimator', exact: true }).click()
    await page.getByText('The Dining Room', { exact: true }).first().waitFor()
    evidence.checks.push('Existing estimator opens and consumes isolated configuration')
    const drawer = page.getByRole('dialog')
    await drawer.getByRole('button', { name: 'Enquire About Your Date', exact: true }).click()
    const estimatorForm = drawer.locator('form')
    await estimatorForm.locator('input[type="tel"]').fill('07700900001')
    await estimatorForm.getByRole('button', { name: 'Continue', exact: true }).click()
    await estimatorForm.getByText('Personal Details', { exact: true }).waitFor()
    const textFields = estimatorForm.locator('input[type="text"]:visible')
    await textFields.nth(0).fill('Isolated')
    await textFields.nth(1).fill('Estimator')
    await estimatorForm.locator('input[type="date"]').fill('2026-12-10')
    await estimatorForm.locator('textarea').fill('Synthetic estimator context')
    await page.clock.fastForward(5000)
    await estimatorForm.getByRole('button', { name: 'Send Inquiry', exact: true }).click()
    await drawer.getByText('Inquiry Received!', { exact: true }).waitFor()
    const estimatorState = await state()
    const estimatorPayload = estimatorState.requests.at(-1).payload
    assert.equal(estimatorPayload.date, '2026-12-10')
    assert.ok(estimatorPayload.notes.includes('The Dining Room'))
    assert.ok(estimatorPayload.notes.includes('Synthetic estimator context'))
    evidence.checks.push('Existing estimator dated enquiry preserves selected room and notes through real proxy into isolated record')
    await page.clock.resume()
    await page.screenshot({ path: `${output}/estimator-mobile.png` })
    await fs.writeFile(`${output}/evidence.json`, JSON.stringify(evidence, null, 2))
    console.log(JSON.stringify(evidence, null, 2))
  } catch (error) {
    await page.screenshot({ path: `${output}/failure.png` }).catch(() => {})
    await fs.writeFile(`${output}/failure.json`, JSON.stringify({ ...evidence, error: String(error) }, null, 2))
    throw error
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
